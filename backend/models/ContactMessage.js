import mongoose from 'mongoose'

const contactMessageSchema = new mongoose.Schema({
  name: {
    type: String,
    required: true,
    trim: true,
  },
  email: {
    type: String,
    required: true,
    trim: true,
    lowercase: true,
  },
  message: {
    type: String,
    required: true,
    trim: true,
  },
  createdAt: {
    type: Date,
    default: Date.now,
  },
}, { versionKey: false })

const ContactMessage = mongoose.model('ContactMessage', contactMessageSchema)

export { ContactMessage }
export default ContactMessage
